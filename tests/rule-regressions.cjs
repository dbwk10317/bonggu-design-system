// readme.md에 명시된 시각·카피 규범 중 소스에서 확정적으로 판별할 수 있는 항목을 검사한다.
// 이 파일은 생성물과 번들을 읽지 않는다. 실패 목록은 원본 파일의 위치와 함께 출력한다.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const SOURCE_EXTENSIONS = new Set(['.jsx', '.js', '.html']);
const COMPONENT_SOURCE_DIRS = ['components', 'templates/dashboard'];
const VISIBLE_SOURCE_DIRS = ['components', 'templates/dashboard', 'guidelines'];
const CSS_DIRS = ['styles', 'tokens'];

function walk(relativeDir, out = []) {
  const absoluteDir = path.join(root, relativeDir);
  if (!fs.existsSync(absoluteDir)) return out;
  for (const entry of fs.readdirSync(absoluteDir, { withFileTypes: true })) {
    const relative = path.posix.join(relativeDir.replaceAll('\\', '/'), entry.name);
    if (entry.isDirectory()) walk(relative, out);
    else out.push(relative);
  }
  return out;
}

function lineOf(text, index) {
  return text.slice(0, index).split('\n').length;
}

function read(relative) {
  return fs.readFileSync(path.join(root, relative), 'utf8');
}

function sourceFiles(dirs, extensions = SOURCE_EXTENSIONS) {
  return dirs
    .flatMap((dir) => walk(dir))
    .filter((file) => extensions.has(path.extname(file).toLowerCase()))
    // support.js is generated by the dashboard runtime and is not a design-system source.
    .filter((file) => !file.endsWith('/support.js'));
}

function cssFiles() {
  return CSS_DIRS.flatMap((dir) => walk(dir)).filter((file) => file.endsWith('.css'));
}

function tokenAliasViolations() {
  const violations = [];
  for (const file of cssFiles().filter((candidate) => candidate.startsWith('tokens/'))) {
    const text = withoutComments(read(file));
    for (const match of text.matchAll(/(--[\w-]+)\s*:\s*var\(\s*(--[\w-]+)\s*\)/g)) {
      violations.push({
        file,
        line: lineOf(text, match.index),
        detail: `${match[1]}:var(${match[2]}) (tokens 별칭 정의 금지)`,
      });
    }
  }
  return violations;
}

function preserveLines(text, pattern) {
  return text.replace(pattern, (match) => match.replace(/[^\n]/g, ' '));
}

function withoutComments(text) {
  return preserveLines(
    preserveLines(
      preserveLines(text, /<!--[\s\S]*?-->/g),
      /\/\*[\s\S]*?\*\//g,
    ),
    /(^|\n)\s*\/\/[^\n]*/g,
  );
}

function withoutNonVisibleMarkup(text) {
  let out = withoutComments(text);
  out = preserveLines(out, /<style\b[^>]*>[\s\S]*?<\/style>/gi);
  out = preserveLines(out, /<script\b[^>]*>[\s\S]*?<\/script>/gi);
  // JSX block comments are not rendered. Attribute values remain because aria-label/title
  // are visible to assistive technology and therefore are part of the copy surface.
  out = preserveLines(out, /\{\/\*[\s\S]*?\*\/\}/g);
  return out;
}

function balanced(text, start, open = '{', close = '}') {
  let depth = 0;
  let quote = null;
  for (let i = start; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      if (ch === '\\') i += 1;
      else if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'" || ch === '`') quote = ch;
    else if (ch === open) depth += 1;
    else if (ch === close && --depth === 0) return text.slice(start + 1, i);
  }
  return text.slice(start + 1);
}

function styleAttributes(text) {
  const found = [];
  for (const match of text.matchAll(/\bstyle\s*=\s*/g)) {
    const start = match.index + match[0].length;
    const ch = text[start];
    if (ch === '{') {
      found.push({ value: balanced(text, start), at: match.index });
    } else if (ch === '"' || ch === "'") {
      let end = start + 1;
      while (end < text.length && text[end] !== ch) {
        if (text[end] === '\\') end += 1;
        end += 1;
      }
      found.push({ value: text.slice(start + 1, end), at: match.index });
    }
  }
  return found;
}

const INLINE_STYLE_PROPERTIES = new Set([
  'color', 'background', 'background-color', 'border-color', 'border-top-color',
  'border-right-color', 'border-bottom-color', 'border-left-color', 'outline-color',
  'text-decoration-color', 'fill', 'stroke',
  'font', 'font-family', 'font-size', 'font-weight', 'font-style', 'line-height',
  'letter-spacing', 'text-decoration',
]);

function inlineStyleViolations() {
  const violations = [];
  for (const file of sourceFiles(COMPONENT_SOURCE_DIRS)) {
    const text = read(file);
    for (const { value, at } of styleAttributes(text)) {
      const body = value.replace(/^\{/, '').replace(/\}$/, '');
      const propertyPattern = /(?:^|[;,])\s*["']?([A-Za-z-]+)["']?\s*[:=]/g;
      for (const match of body.matchAll(propertyPattern)) {
        const property = match[1].toLowerCase();
        if (!INLINE_STYLE_PROPERTIES.has(property)) continue;
        violations.push({
          file,
          line: lineOf(text, at),
          detail: `${property}: inline style`,
        });
      }
    }
  }
  return violations;
}

function emDashViolations() {
  const violations = [];
  for (const file of sourceFiles(VISIBLE_SOURCE_DIRS)) {
    const text = withoutNonVisibleMarkup(read(file));
    for (const match of text.matchAll(/—/g)) {
      violations.push({ file, line: lineOf(text, match.index), detail: '가시 텍스트에 em-dash(—)' });
    }
  }
  return violations;
}

function cssClassViolations() {
  const violations = [];
  // .dark is the documented theme switch. ph-* is the documented self-hosted
  // Phosphor font namespace; both are external contracts rather than DS classes.
  const allowed = (name) => name === 'dark' || name === 'ph-bold' || name.startsWith('ph-');
  for (const file of cssFiles()) {
    const text = withoutComments(read(file));
    for (const block of text.matchAll(/([^{}]+)\{/g)) {
      const selector = block[1];
      for (const match of selector.matchAll(/(?:^|[\s>+~,(])\.([A-Za-z_][A-Za-z0-9_-]*)/g)) {
        const name = match[1];
        if (name.startsWith('bds-') || allowed(name)) continue;
        violations.push({
          file,
          line: lineOf(text, block.index + match.index),
          detail: `.${name} (bds- 접두사 없음)`,
        });
      }
    }
  }
  return violations;
}

function cssRuleBodies(text) {
  const rules = [];
  for (const match of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    rules.push({ selector: match[1], body: match[2], at: match.index });
  }
  return rules;
}

function resolveSize(value, variables) {
  const literal = value.match(/(^|\s|\/)(\d+(?:\.\d+)?)px(?:\s|\/|$)/);
  if (literal) return Number(literal[2]);
  const variable = value.match(/var\(\s*(--[\w-]+)/);
  return variable && variables.has(variable[1]) ? variables.get(variable[1]) : null;
}

function textSizeViolations() {
  const violations = [];
  const variables = new Map();
  for (const file of cssFiles()) {
    const text = withoutComments(read(file));
    for (const match of text.matchAll(/(--[\w-]+)\s*:\s*(\d+(?:\.\d+)?)px\s*;/g)) {
      variables.set(match[1], Number(match[2]));
    }
  }
  for (const file of cssFiles()) {
    const text = withoutComments(read(file));
    for (const rule of cssRuleBodies(text)) {
      // Shorthand `font:` can carry the family, so inspect the whole declaration
      // block instead of requiring a separate `font-family:` property.
      const mono = /--font-(data|mono)|JetBrains Mono|SF Mono|Menlo|Consolas/i.test(`${rule.selector}{${rule.body}`)
        || /\.bds-mono\b/i.test(rule.selector);
      for (const match of rule.body.matchAll(/\bfont-size\s*:\s*([^;]+)/gi)) {
        const size = resolveSize(match[1], variables);
        if (size == null || size >= 11.5 || (size === 10.5 && mono)) continue;
        violations.push({
          file,
          line: lineOf(text, rule.at + match.index),
          detail: `font-size ${size}px${mono ? '' : ' (본문체 또는 mono 맥락 미확인)'}`,
        });
      }
      for (const match of rule.body.matchAll(/\bfont\s*:\s*([^;]+)/gi)) {
        const size = resolveSize(match[1], variables);
        if (size == null || size >= 11.5 || (size === 10.5 && mono)) continue;
        violations.push({
          file,
          line: lineOf(text, rule.at + match.index),
          detail: `font shorthand ${size}px${mono ? '' : ' (본문체 또는 mono 맥락 미확인)'}`,
        });
      }
    }
  }
  return violations;
}

function iconFontNames() {
  const text = read('fonts/phosphor/bold.css');
  return new Set([...text.matchAll(/\.ph-bold\.ph-([A-Za-z0-9-]+)\s*:/g)].map((match) => match[1]));
}

function iconUses() {
  const uses = [];
  const tagPattern = /<([A-Z][A-Za-z0-9.]*)\b[^>]*>/gs;
  for (const file of sourceFiles(COMPONENT_SOURCE_DIRS)) {
    const text = read(file);
    for (const tag of text.matchAll(tagPattern)) {
      const tagText = tag[0];
      const isIcon = tag[1] === 'Icon' || /\bicon\s*=/.test(tagText);
      if (!isIcon) continue;
      const attrs = [];
      for (const match of tagText.matchAll(/\b(?:name|icon)\s*=\s*(["'])([^"']+)\1/g)) {
        attrs.push({ name: match[2], at: tag.index + match.index });
      }
      for (const match of tagText.matchAll(/\b(?:name|icon)\s*=\s*\{([^}]*)\}/g)) {
        const expression = match[1];
        const candidates = expression.includes('?')
          ? [...expression.matchAll(/(?:\?|:)\s*["']([A-Za-z0-9-]+)["']/g)]
          : [...expression.matchAll(/^[\s]*["']([A-Za-z0-9-]+)["']/g)];
        for (const literal of candidates) {
          attrs.push({ name: literal[1], at: tag.index + match.index + literal.index });
        }
      }
      for (const attr of attrs) uses.push({ file, line: lineOf(text, attr.at), name: attr.name });
    }
    for (const match of text.matchAll(/\bicon\s*:\s*(["'])([A-Za-z0-9-]+)\1/g)) {
      uses.push({ file, line: lineOf(text, match.index), name: match[2] });
    }
  }
  return uses;
}

function iconViolations() {
  const names = iconFontNames();
  return iconUses()
    .filter((use) => !names.has(use.name))
    .map((use) => ({ file: use.file, line: use.line, detail: `Icon name "${use.name}"가 fonts/phosphor/bold.css에 없음` }));
}

function printViolations(title, violations, recommendation) {
  if (!violations.length) return;
  console.error(`\n${title}: ${violations.length}건`);
  for (const violation of violations) {
    console.error(`  ${violation.file}:${violation.line}  ${violation.detail}`);
  }
  console.error(`  권장 수정: ${recommendation}`);
}

const checks = [
  ['em-dash', emDashViolations(), '가시 문구의 —를 가운뎃점(·), 쉼표 또는 문장 분리로 바꿉니다.'],
  ['inline style 색·폰트', inlineStyleViolations(), '색·폰트 선언을 tokens/styles의 bds- 클래스와 토큰으로 옮깁니다.'],
  ['CSS class prefix', cssClassViolations(), '공개·내부 CSS 클래스에 bds- 접두사를 붙이고, 외부 계약이 아니면 기존 이름을 제거합니다.'],
  ['토큰 별칭', tokenAliasViolations(), 'tokens/*.css에서 --x:var(--y) 별칭을 제거하고 정본 토큰과 사용처를 직접 이관합니다.'],
  ['본문 글자 크기', textSizeViolations(), '본문체는 11.5px 이상으로 올리고, 10.5px은 mono 단위·타임스탬프에만 사용합니다.'],
  ['Phosphor Bold 아이콘 이름', iconViolations(), 'fonts/phosphor/bold.css에 있는 이름으로 바꾸거나 해당 아이콘을 추가합니다.'],
];

let failed = 0;
for (const [title, violations, recommendation] of checks) {
  printViolations(title, violations, recommendation);
  failed += violations.length;
}

if (failed) {
  console.error(`\nFAIL rule regressions: ${failed}건. 위반을 수정한 뒤 다시 실행하세요.`);
  process.exit(1);
}
console.log('PASS rule regressions: readme 기계 규칙 6종');
